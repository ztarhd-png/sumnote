const path = require('node:path');
const { chromium } = require('./.tools/node_modules/playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
  const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox'] });
  const context = await browser.newContext({ acceptDownloads: true, viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2, locale: 'ko-KR' });
  const page = await context.newPage();
  const errors = [];
  const external = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => { if (!r.url().startsWith(process.env.TEST_URL || 'http://127.0.0.1:8765') && !r.url().startsWith('data:')) external.push(r.url()); });
  const base = process.env.TEST_URL || 'http://127.0.0.1:8765';
  fs.mkdirSync(path.join(__dirname, 'screenshots'), { recursive: true });
  await page.goto(base, { waitUntil: 'load' });
  await page.locator('#mobile-new').click();
  await page.locator('#name-input').fill('11월 장부');
  await page.locator('#name-form button[type=submit]').click();
  await page.locator('#note-title').fill('11월 장부');
  await page.locator('#note-body').fill('커피 4,500\n식비 1.5만원\n환불 −5000원\n3만\n2천\n12000*3\n# 제외 99999');
  await page.waitForTimeout(200);
  assert.equal(await page.locator('#note-total').innerText(), '82,500');
  const expectedBody = await page.locator('#note-body').inputValue();
  const stored = await page.evaluate(() => JSON.parse(localStorage.getItem('sumnote.data.v1')));
  assert.equal(stored.notes.find(n => n.title === '11월 장부').body, expectedBody, 'localStorage 본문 자동 저장');
  assert.equal(await page.locator('#valued-count').innerText(), '6개 줄을 더했어요');
  await page.screenshot({ path: '/workspace/apps/sumnote/screenshots/01-iphone-editor.png', fullPage: true });
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal(await page.locator('#note-title').inputValue(), '11월 장부', '새로고침 후 복원');
  assert.equal(await page.locator('#note-total').innerText(), '82,500');
  assert.equal(await page.locator('#note-body').inputValue(), expectedBody, '본문 복원');
  await page.locator('#search').fill('환불');
  await page.waitForTimeout(100);
  assert.equal(await page.locator('#search-summary').innerText(), '노트 1개 · 일치하는 줄 1개 · 매칭 라인 합계 -5,000원');
  assert.equal(await page.locator('.note-card').count(), 1);
  await page.screenshot({ path: '/workspace/apps/sumnote/screenshots/02-iphone-search.png', fullPage: true });
  await page.locator('#search').fill('존재하지않는검색어');
  assert.equal(await page.locator('.note-card').count(), 0);
  assert.equal(await page.locator('#search-summary').innerText(), '노트 0개 · 일치하는 줄 0개 · 매칭 라인 합계 0원');
  await page.locator('#search').fill('');
  const csvWait = page.waitForEvent('download');
  await page.locator('#export-csv').click();
  const csv = await csvWait;
  assert.match(csv.suggestedFilename(), /\.csv$/);
  await csv.saveAs('/workspace/apps/sumnote/screenshots/test-export.csv');
  assert.match(fs.readFileSync('/workspace/apps/sumnote/screenshots/test-export.csv', 'utf8'), /커피 4,500/);
  const csvText = fs.readFileSync('/workspace/apps/sumnote/screenshots/test-export.csv', 'utf8');
  assert.ok(csvText.startsWith('\uFEFF'));
  assert.ok(csvText.includes('"환불 −5000원","-5000"'));
  assert.ok(csvText.includes('"12000*3","36000"'));
  assert.ok(csvText.includes('"# 제외 99999",""'));
  await page.locator('#menu-toggle').click();
  assert.equal(await page.locator('#menu-toggle').getAttribute('aria-expanded'), 'true');
  await page.locator('#settings').click();
  const backupWait = page.waitForEvent('download');
  await page.locator('#backup').click();
  const backup = await backupWait;
  await backup.saveAs(path.join(__dirname, 'screenshots/test-backup.json'));
  const data = JSON.parse(fs.readFileSync(path.join(__dirname, 'screenshots/test-backup.json'), 'utf8'));
  assert.ok(data.notes.some(n => n.title === '11월 장부'));
  assert.deepEqual(data, await page.evaluate(() => JSON.parse(localStorage.getItem('sumnote.data.v1'))));
  await page.locator('#import-file').setInputFiles({ name: 'invalid.json', mimeType: 'application/json', buffer: Buffer.from('{}') });
  await page.waitForFunction(() => document.querySelector('#toast').textContent.includes('백업 파일인지'));
  assert.deepEqual(await page.evaluate(() => JSON.parse(localStorage.getItem('sumnote.data.v1'))), data, '잘못된 JSON은 원본 유지');
  await page.locator('#import-file').setInputFiles(path.join(__dirname, 'screenshots/test-backup.json'));
  await page.waitForFunction(count => JSON.parse(localStorage.getItem('sumnote.data.v1')).notes.length === count * 2, data.notes.length);
  const imported = await page.evaluate(() => JSON.parse(localStorage.getItem('sumnote.data.v1')));
  assert.equal(new Set(imported.notes.map(n => n.id)).size, imported.notes.length);
  for (const note of data.notes) {
    const restored = imported.notes.find(n => n.id !== note.id && n.title === note.title && n.body === note.body);
    assert.ok(restored, 'JSON 노트 복원: ' + note.title);
    if (note.folderId) assert.equal(imported.folders.find(f => f.id === restored.folderId).name, data.folders.find(f => f.id === note.folderId).name);
  }
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal(await page.locator('#note-total').innerText(), '82,500');
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.screenshot({ path: '/workspace/apps/sumnote/screenshots/03-iphone-dark.png', fullPage: true });
  const sw = await page.evaluate(async () => !!(await navigator.serviceWorker?.ready));
  assert.equal(sw, true, '서비스 워커 오프라인 준비');
  await page.waitForFunction(() => !!navigator.serviceWorker.controller);
  await context.setOffline(true);
  const response = await page.reload({ waitUntil: 'load' });
  assert.ok(response.fromServiceWorker(), '오프라인 문서 캐시 응답');
  assert.equal(await page.locator('#note-total').innerText(), '82,500');
  await page.locator('#note-body').fill(expectedBody + '\n오프라인 1000');
  assert.equal(await page.locator('#note-total').innerText(), '83,500');
  await page.reload({ waitUntil: 'load' });
  assert.equal(await page.locator('#note-body').inputValue(), expectedBody + '\n오프라인 1000');
  assert.equal(await page.locator('#note-total').innerText(), '83,500');
  await page.screenshot({ path: path.join(__dirname, 'screenshots/04-iphone-offline.png'), fullPage: true });
  await context.setOffline(false);
  assert.equal(errors.length, 0, 'JavaScript 오류 없음: ' + errors.join(', '));
  assert.equal(external.length, 0, '외부 네트워크 요청 없음: ' + external.join(', '));
  const layout = await page.evaluate(() => ({ viewport: innerWidth, width: document.documentElement.scrollWidth, inputFont: getComputedStyle(document.querySelector('#note-body')).fontSize }));
  assert.equal(layout.width, 390, '가로 넘침 없음');
  assert.ok(parseFloat(layout.inputFont) >= 16, 'iOS 확대 방지 입력 폰트');
  console.log('브라우저 테스트 통과: 노트/합계/자동저장/복원/검색합계/CSV/JSON/오프라인/다크/390px');
  console.log(JSON.stringify(layout));
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
