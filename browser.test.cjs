const { chromium } = require('./.tools/node_modules/playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
(async () => {
  const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox'] });
  const context = await browser.newContext({ acceptDownloads: true, viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 2, locale: 'ko-KR' });
  const page = await context.newPage();
  const errors = [];
  const external = [];
  page.on('pageerror', e => errors.push(e.message));
  page.on('request', r => { if (!r.url().startsWith(process.env.TEST_URL || 'http://127.0.0.1:8765') && !r.url().startsWith('data:')) external.push(r.url()); });
  const base = process.env.TEST_URL || 'http://127.0.0.1:8765';
  await page.goto(base, { waitUntil: 'load' });
  await page.getByRole('button', { name: '새 노트', exact: true }).first().click({ force: true });
  await page.locator('#name-input').fill('11월 장부');
  await page.locator('#name-form button[type=submit]').click({ force: true });
  await page.locator('#note-title').fill('11월 장부');
  await page.locator('#note-body').fill('커피 4,500\n식비 1.5만원\n환불 −5000원\n3만\n2천\n12000*3\n# 제외 99999');
  await page.waitForTimeout(200);
  assert.equal(await page.locator('#note-total').innerText(), '87,500');
  const stored = await page.evaluate(() => localStorage.length > 0);
  assert.equal(stored, true, 'localStorage 자동 저장');
  await page.screenshot({ path: '/workspace/apps/sumnote/screenshots/01-iphone-editor.png', fullPage: true });
  await page.reload({ waitUntil: 'networkidle' });
  assert.equal(await page.locator('#note-title').inputValue(), '11월 장부', '새로고침 후 복원');
  assert.equal(await page.locator('#note-total').innerText(), '87,500');
  await page.locator('#search').fill('환불');
  await page.waitForTimeout(100);
  assert.match(await page.locator('#search-summary').innerText(), /-?5,?000|−5,?000/);
  await page.screenshot({ path: '/workspace/apps/sumnote/screenshots/02-iphone-search.png', fullPage: true });
  await page.locator('#search').fill('');
  const csvWait = page.waitForEvent('download');
  await page.locator('#export-csv').click();
  const csv = await csvWait;
  assert.match(csv.suggestedFilename(), /\.csv$/);
  await csv.saveAs('/workspace/apps/sumnote/screenshots/test-export.csv');
  assert.match(fs.readFileSync('/workspace/apps/sumnote/screenshots/test-export.csv', 'utf8'), /커피 4,500/);
  await page.locator('#settings').evaluate(el => el.click());
  const backupWait = page.waitForEvent('download');
  await page.locator('#backup').click();
  const backup = await backupWait;
  await backup.saveAs('/tmp/sumnote-test-backup.json');
  const data = JSON.parse(fs.readFileSync('/tmp/sumnote-test-backup.json', 'utf8'));
  assert.ok(data.notes.some(n => n.title === '11월 장부'));
  await page.locator('#settings-dialog [data-close]').click();
  await page.emulateMedia({ colorScheme: 'dark' });
  await page.screenshot({ path: '/workspace/apps/sumnote/screenshots/03-iphone-dark.png', fullPage: true });
  const sw = await page.evaluate(async () => !!(await navigator.serviceWorker?.ready));
  assert.equal(sw, true, '서비스 워커 오프라인 준비');
  assert.equal(errors.length, 0, 'JavaScript 오류 없음: ' + errors.join(', '));
  assert.equal(external.length, 0, '외부 네트워크 요청 없음: ' + external.join(', '));
  const layout = await page.evaluate(() => ({ viewport: innerWidth, width: document.documentElement.scrollWidth, inputFont: getComputedStyle(document.querySelector('#note-body')).fontSize }));
  assert.equal(layout.width, 390, '가로 넘침 없음');
  assert.ok(parseFloat(layout.inputFont) >= 16, 'iOS 확대 방지 입력 폰트');
  console.log('브라우저 테스트 통과: 노트/합계/자동저장/복원/검색합계/CSV/JSON/오프라인/다크/390px');
  console.log(JSON.stringify(layout));
  await browser.close();
})().catch(e => { console.error(e); process.exit(1); });
